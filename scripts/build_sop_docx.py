class PlaybookRenderer(engine.Renderer):
    """复用引擎排版能力，仅替换封面页眉标（去掉学习手册字样）。"""

    def cover(self, title, subtitle, meta):
        d = self.doc
        for _ in range(4):
            p = d.add_paragraph()
            engine._spacing(p, 0, 0, 1.0)

        p = d.add_paragraph()
        engine._spacing(p, 0, 6, 1.0)
        r = p.add_run("S A L E S   P L A Y B O O K")
        engine._set_run_font(r, engine.FONT_EN, engine.FONT_EN, Pt(11),
                             bold=True, color=engine.BLUE)

        p = d.add_paragraph()
        engine._spacing(p, 0, 0, 1.0)
        engine._horizon_rule(p, engine.NAVY, 24, 0, 14)

        p = d.add_paragraph()
        engine._spacing(p, 0, 8, 1.15)
        r = p.add_run(title)
        engine._set_run_font(r, engine.FONT_H, engine.FONT_EN, Pt(28),
                             bold=True, color=engine.NAVY)

        p = d.add_paragraph()
        engine._spacing(p, 0, 16, 1.3)
        r = p.add_run(subtitle)
        engine._set_run_font(r, engine.FONT_H, engine.FONT_H, Pt(13), color=engine.GREY)

        for _ in range(3):
            p = d.add_paragraph()
            engine._spacing(p, 0, 0, 1.0)

        tbl = d.add_table(rows=len(meta), cols=2)
        tbl.alignment = WD_TABLE_ALIGNMENT.LEFT
        engine._no_borders_table(tbl)
        for i, (k, v) in enumerate(meta):
            c0, c1 = tbl.rows[i].cells
            c0.width = Cm(3.0)
            c1.width = Cm(13.2)
            engine._cell_margins(c0, 40, 40, 0, 160)
            engine._cell_margins(c1, 40, 40, 0, 0)
            pa = c0.paragraphs[0]
            engine._spacing(pa, 0, 0, 1.35)
            engine._set_run_font(pa.add_run(k), engine.FONT_H, engine.FONT_EN, Pt(10),
                                 bold=True, color=engine.BLUE)
            pb = c1.paragraphs[0]
            engine._spacing(pb, 0, 0, 1.35)
            engine._set_run_font(pb.add_run(v), engine.FONT_B, engine.FONT_EN, Pt(10),
                                 color=engine.INK)

        for _ in range(2):
            p = d.add_paragraph()
            engine._spacing(p, 0, 0, 1.0)

        p = d.add_paragraph()
        engine._spacing(p, 0, 0, 1.0)
        engine._horizon_rule(p, "D0D7E5", 6, 0, 8)
        p = d.add_paragraph()
        engine._spacing(p, 0, 0, 1.3)
        engine._set_run_font(
            p.add_run("说明：本文为内部销售作业工具，话术模板需按客户所属行业与规模做"
                      "个性化替换后使用；文中金额与效果数据以实际项目测算为准。"),
            engine.FONT_B, engine.FONT_EN, Pt(9), color=engine.GREY)


